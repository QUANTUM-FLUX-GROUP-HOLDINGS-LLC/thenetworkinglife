document.addEventListener('DOMContentLoaded', () => {
  const selector = document.getElementById('lang-selector');
  if (!selector) return;

  // Función para cambiar los textos
  const applyLanguage = (lang) => {
    const dict = translations[lang] || translations.en;
    
    // Cambiar el atributo lang del HTML
    document.documentElement.lang = lang;

    // Buscar todos los elementos con data-i18n y actualizarlos
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });
  };

  // Escuchar el cambio en el selector
  selector.addEventListener('change', (e) => {
    const lang = e.target.value;
    localStorage.setItem('tnl-lang', lang);
    applyLanguage(lang);
  });

  // Auto-detectar o cargar el idioma guardado
  const savedLang = localStorage.getItem('tnl-lang');
  if (savedLang && translations[savedLang]) {
    selector.value = savedLang;
    applyLanguage(savedLang);
  } else {
    // Si es la primera vez, intenta usar el idioma del navegador (opcional)
    const browserLang = navigator.language.split('-')[0];
    if (translations[browserLang]) {
      selector.value = browserLang;
      applyLanguage(browserLang);
    }
  }
});
